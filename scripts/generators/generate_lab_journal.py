    print(f"[OK] Saved MD: {md_path}")
    
    # 2. Сохраняем HTML для печати
    html_path = os.path.join(DOCS_DIR, "Лабораторный_журнал_исследования_Ковалева_Алиса.html")
    html_content = make_html_journal()
    with open(html_path, "w", encoding="utf-8") as f:
        f.write(html_content)
    print(f"[OK] Saved HTML: {html_path}")
    
    # 3. Генерируем PDF через Chrome
    pdf_path = os.path.join(DOCS_DIR, "Лабораторный_журнал_исследования_Ковалева_Алиса.pdf")
    user_pdf_path = os.path.join(USER_DOCS, "Лабораторный_журнал_исследования_Ковалева_Алиса.pdf")
    if os.path.exists(CHROME_PATH):
        cmd = [
            CHROME_PATH,
            "--headless=new",
            "--disable-gpu",
            "--no-pdf-header-footer",
            f"--print-to-pdf={pdf_path}",
            html_path
        ]
        res = subprocess.run(cmd, capture_output=True)
        if res.returncode == 0 and os.path.exists(pdf_path):
            shutil.copy2(pdf_path, user_pdf_path)
            print(f"[OK] Saved PDF: {pdf_path} ({os.path.getsize(pdf_path)/1024:.1f} KB)")
            print(f"[OK] Copied to Documents: {user_pdf_path}")
        else:
            print(f"[Warn] Chrome PDF compilation issue: {res.stderr}")
            
    # 4. Генерируем Word (.docx)
    docx_path = os.path.join(DOCS_DIR, "Лабораторный_журнал_исследования_Ковалева_Алиса.docx")
    user_docx_path = os.path.join(USER_DOCS, "Лабораторный_журнал_исследования_Ковалева_Алиса.docx")
