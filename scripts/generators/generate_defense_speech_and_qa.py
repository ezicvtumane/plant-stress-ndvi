def md_to_html_speech(md_text):
    import re
    # Конвертируем заголовки и бейджи
    lines = md_text.split('\n')
    out = []
    for line in lines:
        if line.startswith('# '):
            out.append(f"<h1>{line[2:]}</h1>")
        elif line.startswith('### '):
            out.append(f"<h2>{line[4:]}</h2>")
        elif line.startswith('**[Слайд'):
            m = re.match(r'\*\*\[(.*?)\]\*\*\s*\*(.*?)\*', line)
            if m:
                out.append(f"<p><span class='slide-badge'>{m.group(1)}</span> <span class='time-badge'>{m.group(2)}</span></p>")
            else:
                out.append(f"<p><b>{line}</b></p>")
        elif line.startswith('> [!TIP]'):
            out.append("<div class='tip-box'><b>💡 Советы перед выходом:</b><ul>")
        elif line.startswith('> * '):
            out.append(f"<li>{line[4:]}</li>")
        elif line.startswith('> '):
            out.append(f"</ul></div>")
        elif line.strip().startswith('«') or line.strip().startswith('«Здравствуйте'):
            out.append(f"<blockquote>{line}</blockquote>")
        elif line.startswith('---'):
            out.append("<hr style='border:0; border-top:1px solid #e2e8f0; margin:12pt 0;'>")
        elif line.strip():
            # Заменяем жирный текст
            l_fmt = re.sub(r'\*\*(.*?)\*\*', r'<b>\1</b>', line)
            l_fmt = re.sub(r'\*(.*?)\*', r'<i>\1</i>', l_fmt)
            out.append(f"<p>{l_fmt}</p>")
    return '\n'.join(out)

def md_to_html_qa(md_text):
    import re
    lines = md_text.split('\n')
    out = []
    in_box = False
    cur_q = ""
    cur_hint = ""
    cur_a = ""

    for line in lines:
        if line.startswith('# '):
            out.append(f"<h1>{line[2:]}</h1>")
        elif line.startswith('### Вопрос'):
            if in_box:
                out.append(f"""<div class='qa-box'>
                    <div class='qa-q'>{cur_q}</div>
                    <div class='qa-hint'>{cur_hint}</div>
                    <div class='qa-a'>{cur_a}</div>
                </div>""")
            in_box = True
            cur_q = f"<b>{line[4:]}</b>"
            cur_hint = ""
            cur_a = ""
        elif line.startswith('**Жюри:**'):
            cur_q += "<br>" + line
        elif line.startswith('> **Психология'):
            cur_hint = line[2:]
        elif line.startswith('> *«') or line.startswith('> '):
            cur_a += line[2:] + " "
        elif line.startswith('---'):
            pass
        elif line.strip() and not in_box:
            l_fmt = re.sub(r'\*\*(.*?)\*\*', r'<b>\1</b>', line)
            out.append(f"<p>{l_fmt}</p>")

    if in_box:
        out.append(f"""<div class='qa-box'>
            <div class='qa-q'>{cur_q}</div>
            <div class='qa-hint'>{cur_hint}</div>
            <div class='qa-a'>{cur_a}</div>
        </div>""")
    return '\n'.join(out)

