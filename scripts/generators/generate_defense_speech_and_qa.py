def compile_pdf(html_path, pdf_name):
    pdf_docs_path = os.path.join(DOCS_DIR, pdf_name)
    pdf_user_docs = os.path.join(USER_DOCS, pdf_name)
    pdf_static = os.path.join(STATIC_DIR, pdf_name)
    
    if os.path.exists(CHROME_PATH):
        cmd = [
            CHROME_PATH,
            "--headless",
            "--disable-gpu",
            "--no-pdf-header-footer",
            "--run-all-compositor-stages-before-draw",
            f"--print-to-pdf={pdf_docs_path}",
            html_path
        ]
        subprocess.run(cmd, check=True)
        if os.path.exists(pdf_docs_path):
            shutil.copyfile(pdf_docs_path, pdf_user_docs)
            shutil.copyfile(pdf_docs_path, pdf_static)
            sz = os.path.getsize(pdf_docs_path) / 1024
            print(f"[SUCCESS] Compiled {pdf_name} ({sz:.1f} KB) -> Documents/ & static/")

