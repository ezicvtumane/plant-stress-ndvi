def set_slide_bg(slide):
    bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, Inches(13.333), Inches(7.5))
    bg.fill.solid()
    bg.fill.fore_color.rgb = DARK_BG
    bg.line.fill.background()
    return bg

def add_header(slide, tag_text, slide_num):
    tx = slide.shapes.add_textbox(Inches(0.8), Inches(0.4), Inches(9.0), Inches(0.5))
    p = tx.text_frame.paragraphs[0]
    p.text = "БОЛЬШИЕ ВЫЗОВЫ 2026  •  " + tag_text.upper()
    p.font.size = Pt(10)
    p.font.bold = True
    p.font.color.rgb = EMERALD

    tx_r = slide.shapes.add_textbox(Inches(10.0), Inches(0.4), Inches(2.5), Inches(0.5))
    p_r = tx_r.text_frame.paragraphs[0]
    p_r.alignment = PP_ALIGN.RIGHT
    p_r.text = f"{slide_num:02d} / 14"
    p_r.font.size = Pt(11)
    p_r.font.bold = True
    p_r.font.color.rgb = SKY_BLUE

def add_title(slide, title_text, subtitle_text=""):
    tx = slide.shapes.add_textbox(Inches(0.8), Inches(0.9), Inches(11.7), Inches(1.1))
    tf = tx.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = title_text
    p.font.size = Pt(22)
    p.font.bold = True
    p.font.color.rgb = WHITE
    if subtitle_text:
        p2 = tf.add_paragraph()
        p2.text = subtitle_text
        p2.font.size = Pt(12)
        p2.font.color.rgb = MUTED

